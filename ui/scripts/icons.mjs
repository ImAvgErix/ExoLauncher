// Exo's icons are Tabler's (brand/icons.tsx). This writes the glyphs icons.tsx names, and each one's -filled where
// Tabler draws one, into brand/tabler.ts as path data, so only those ship. Run it after changing a glyph in
// icons.tsx: npm run icons (check-only with --check).
import fs from 'node:fs'
import path from 'node:path'
import tabler from '@iconify-json/tabler/icons.json' with { type: 'json' }
import info from '@iconify-json/tabler/info.json' with { type: 'json' }

const brand = path.resolve(import.meta.dirname, '../src/brand')
const source = fs.readFileSync(path.join(brand, 'icons.tsx'), 'utf8')
const out = path.join(brand, 'tabler.ts')

// icon('library', 'layout-grid') and marked('hash-lock', 'hash', 'lock-filled'): the glyph and its badge.
const names = new Set()
for (const [, glyph, badge] of source.matchAll(/(?:icon|marked)\('[^']+', '([a-z0-9-]+)'(?:, '([a-z0-9-]+)')?/g)) {
  for (const name of [glyph, badge]) {
    if (!name) continue
    if (!tabler.icons[name]) throw new Error(`Tabler has no glyph "${name}"`)
    names.add(name)
    if (!name.endsWith('-filled') && tabler.icons[`${name}-filled`]) names.add(`${name}-filled`)
  }
}

// A glyph's paths, each drawn by its line (0), filled (1) or both (2), as Tabler's SVG has them: its paths, or one
// group whose fill and stroke the paths inherit unless they set their own.
const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1]
const parts = name => {
  const body = tabler.icons[name].body
  const group = body.startsWith('<g') ? body.slice(0, body.indexOf('>') + 1) : ''
  const out = []
  for (const [tag] of body.matchAll(/<path[^>]*\/>/g)) {
    const fill = (attr(tag, 'fill') ?? attr(group, 'fill') ?? 'currentColor') === 'currentColor'
    const stroke = (attr(tag, 'stroke') ?? attr(group, 'stroke') ?? 'none') === 'currentColor'
    if (fill || stroke) out.push([stroke ? (fill ? 2 : 0) : 1, attr(tag, 'd')])
  }
  const shapes = body.replace(/<\/?g[^>]*>/g, '').replace(/<path[^>]*\/>/g, '')
  if (shapes || !out.length) throw new Error(`${name}: only paths are read (${body.slice(0, 80)})`)
  if (out.some(([kind]) => kind !== 1) && attr(group || body, 'stroke-width') !== '2') throw new Error(`${name}: not Tabler's 2 px line`)
  return out
}

const lines = [...names].sort().map(name => `  '${name}': ${JSON.stringify(parts(name))},`)
const next = `// Generated by scripts/icons.mjs from ${info.name} ${info.version} (${info.author.name}, ${info.license.spdx}): the
// glyphs brand/icons.tsx draws, on Tabler's ${tabler.width} grid; each path is drawn by its line (0), filled (1) or both (2).
// Don't edit; run npm run icons.
export const TABLER = {
${lines.join('\n')}
} as const satisfies Record<string, readonly (readonly [0 | 1 | 2, string])[]>
`
// Compared with LF line ends: a Windows checkout (CI's runner, core.autocrlf) has CRLF, which read as out of date.
const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : ''
if (process.argv.includes('--check')) {
  if (next !== current) { console.error('brand/tabler.ts is out of date; run npm run icons'); process.exit(1) }
} else if (next !== current) fs.writeFileSync(out, next)
console.log(`${names.size} glyphs`)
