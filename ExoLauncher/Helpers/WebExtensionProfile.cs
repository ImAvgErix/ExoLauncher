using System.Text.Json;
using Microsoft.Web.WebView2.Core;

namespace ExoLauncher.Helpers;

/// <summary>One-time default configuration for bundled provider extensions,
/// applied through the extension's own options page storage API.</summary>
internal static class WebExtensionProfile
{
    internal const string Revision = "exo-ext-1";

    // SponsorBlock: only music_offtopic auto-skips, only on YouTube Music; no
    // skip notice, player buttons, submission UI, donation links or popups.
    private const string SponsorBlockScript = """
        (() => {
          if (location.protocol !== 'chrome-extension:' || !globalThis.chrome?.storage?.sync) return false;
          if (window.__exoExtensionProfile) return true;
          window.__exoExtensionProfile = { state: 'pending' };
          const seed = {
            categorySelections: [
              { name: 'music_offtopic', option: 2 },
              { name: 'sponsor', option: -1 }, { name: 'selfpromo', option: -1 },
              { name: 'interaction', option: -1 }, { name: 'intro', option: -1 },
              { name: 'outro', option: -1 }, { name: 'preview', option: -1 },
              { name: 'filler', option: -1 }, { name: 'poi_highlight', option: -1 },
              { name: 'exclusive_access', option: -1 }, { name: 'chapter', option: -1 },
              { name: 'hook', option: -1 },
            ],
            skipNonMusicOnlyOnYoutubeMusic: true,
            autoSkipOnMusicVideos: false,
            dontShowNotice: true,
            showUpcomingNotice: false,
            hideVideoPlayerControls: true,
            hideInfoButtonPlayerControls: true,
            hideDeleteButtonPlayerControls: true,
            hideUploadButtonPlayerControls: true,
            hideSkipButtonPlayerControls: true,
            hideDiscordLink: true,
            showDonationLink: false,
            showUpsells: false,
            showNewFeaturePopups: false,
            showDeArrowPromotion: false,
            showDeArrowInSettings: false,
            shownDeArrowPromotion: true,
            showCategoryGuidelines: false,
            showChapterInfoMessage: false,
            showSegmentNameInChapterBar: false,
            showAutogeneratedChapters: false,
            showCreatorChapters: false,
            cleanPopup: true,
            hideSegmentCreationInPopup: true,
            audioNotificationOnSkip: false,
          };
          chrome.storage.sync.set(seed, () => {
            if (chrome.runtime.lastError) {
              window.__exoExtensionProfile = { state: 'failed', error: String(chrome.runtime.lastError.message).slice(0, 200) };
              return;
            }
            window.__exoExtensionProfile = { state: 'ready' };
          });
          return true;
        })();
        """;

    private static string? OptionsPage(WebExtensions.Entry entry) => entry.Key switch
    {
        "sponsorblock" => "options/options.html",
        _ => null,
    };

    private static string? Script(WebExtensions.Entry entry) => entry.Key switch
    {
        "sponsorblock" => SponsorBlockScript,
        _ => null,
    };

    internal static async Task<bool> ApplyAsync(CoreWebView2 source, WebExtensions.Entry entry, string extensionId, nint owner)
    {
        var page = OptionsPage(entry);
        var script = Script(entry);
        if (page is null || script is null) return true; // Nothing to seed.
        CoreWebView2Controller? controller = null;
        var stage = "create controller";
        try
        {
            var options = source.Environment.CreateCoreWebView2ControllerOptions();
            options.ProfileName = source.Profile.ProfileName;
            options.IsInPrivateModeEnabled = source.Profile.IsInPrivateModeEnabled;
            controller = await source.Environment.CreateCoreWebView2ControllerAsync(
                CoreWebView2ControllerWindowReference.CreateFromWindowHandle((ulong)owner), options);
            controller.IsVisible = false;
            stage = "load options page";
            var core = controller.CoreWebView2;
            core.Settings.AreHostObjectsAllowed = false;
            core.Settings.IsWebMessageEnabled = false;
            core.Settings.AreDevToolsEnabled = false;
            core.Settings.AreDefaultScriptDialogsEnabled = false;
            var uri = "chrome-extension://" + extensionId + "/" + page;
            var ready = new TaskCompletionSource<bool>(TaskCreationOptions.RunContinuationsAsynchronously);
            core.NavigationStarting += (_, e) => { if (e.Uri != uri) e.Cancel = true; };
            core.NewWindowRequested += (_, e) => e.Handled = true;
            core.NavigationCompleted += (_, e) => ready.TrySetResult(e.IsSuccess && core.Source == uri);
            core.Navigate(uri);
            if (!await ready.Task.WaitAsync(TimeSpan.FromSeconds(8))) throw new InvalidOperationException("Options page navigation failed");
            stage = "save configuration";
            if (await core.ExecuteScriptAsync(script) != "true") throw new InvalidOperationException("Extension storage API unavailable");
            var deadline = Environment.TickCount64 + 15000;
            while (Environment.TickCount64 < deadline)
            {
                using var state = JsonDocument.Parse(await core.ExecuteScriptAsync("window.__exoExtensionProfile ?? null"));
                if (state.RootElement.ValueKind == JsonValueKind.Object)
                {
                    var status = state.RootElement.GetProperty("state").GetString();
                    if (status == "ready") return true;
                    if (status == "failed") throw new InvalidOperationException(state.RootElement.GetProperty("error").GetString());
                }
                await Task.Delay(200);
            }
            throw new TimeoutException("Configuration did not finish");
        }
        catch (Exception error)
        {
            AppLog.Warn(entry.Title + " profile " + stage + ": " + error.Message);
            return false;
        }
        finally { try { controller?.Close(); } catch { } }
    }
}
